-- MUC 3-4 (17/11/2026): LUONG CACH MOI + TI LE. Chi them bang moi, khong doi bang/cot cu.
-- Chay 1 lan trong Supabase > SQL Editor (chon "Run without RLS" nhu muc 2). Chay lai khong hai gi.
-- Muon bo "cach moi" sau nay: drop 5 bang duoi day.

-- 1. Ngay dac biet (le / shipper nghi / san loi): bo khoi tu va mau cua thuong 16h, van tinh ngay cong va chia quy.
create table if not exists public.warehouse_special_days (
  ngay date primary key,
  loai text not null check (loai in ('le','shipper_nghi','san_loi')),
  ghi_chu text,
  nguoi_dat text,
  created_at timestamptz not null default now()
);

-- 2. Log dat / sua / bo ngay dac biet
create table if not exists public.warehouse_special_days_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  ngay date not null,
  action text not null check (action in ('set','edit','unset')),
  loai text,
  ghi_chu text,
  by_staff text
);

-- 3. Don tre truoc 16h theo ngay + san. CHUA co man nhap, CHUA co job tu chay (se lam sau).
--    trang_thai: ok | thieu_du_lieu | nghi_ngo | dac_biet. Chi ngay co moi san deu "ok" moi duoc tinh thuong.
create table if not exists public.warehouse_cutoff_daily (
  id bigint generated by default as identity primary key,
  ngay date not null,
  san text not null,                        -- tiktok | shopee
  mau_so int not null default 0,            -- so don den han truoc 16h
  tu_so int not null default 0,             -- so don tre
  ma_don_tre jsonb not null default '[]'::jsonb,
  trang_thai text not null default 'ok' check (trang_thai in ('ok','thieu_du_lieu','nghi_ngo','dac_biet')),
  ghi_chu text,
  created_at timestamptz not null default now(),
  unique (ngay, san)
);

-- 3b. Chi tiet cac don TRE truoc 16h (de bam "Xem them" o tab Tong quan). Job 20:00 tren PC ghi vao day
--     va TU XOA dong cu hon 40 ngay (chot 17/11/2026). Con so mau/tu tong hop o bang tren giu lai, khong xoa.
create table if not exists public.warehouse_cutoff_orders (
  id bigint generated by default as identity primary key,
  ngay date not null,                       -- ngay den han (don tao tu 16:00 hom truoc den 16:00 ngay nay)
  san text not null,
  ma_don text not null,                     -- ma don cua san
  ma_van_don text,
  tao_luc timestamptz,
  tinh_trang text,                          -- 'Chua xu ly' | 'Da xu ly, cho lay'
  created_at timestamptz not null default now(),
  unique (ngay, san, ma_don)
);
create index if not exists warehouse_cutoff_orders_ngay_idx on public.warehouse_cutoff_orders (ngay);

-- 4. Kien hoan quet trung (co ma da quet): luu co trung, KHONG cong tien lan 2.
--    (warehouse_return_checks da co rang buoc duy nhat theo ma nen dong thu 2 khong bao gio duoc luu; bang nay ghi lai lan quet trung.)
create table if not exists public.warehouse_return_dup_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  code text not null,
  platform text,
  staff text,
  first_scanned_at timestamptz,
  first_staff text
);
create index if not exists warehouse_return_dup_log_code_idx on public.warehouse_return_dup_log (code);

-- 5. Quyen: giong muc 2
alter table public.warehouse_special_days disable row level security;
alter table public.warehouse_special_days_log disable row level security;
alter table public.warehouse_cutoff_daily disable row level security;
alter table public.warehouse_cutoff_orders disable row level security;
alter table public.warehouse_return_dup_log disable row level security;
grant select, insert, update, delete on
  public.warehouse_special_days, public.warehouse_special_days_log,
  public.warehouse_cutoff_daily, public.warehouse_cutoff_orders, public.warehouse_return_dup_log to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
