-- Muon bo "cach moi" sau nay: drop 2 bang log + drop cot co_staff (cach cu khong dung toi chung).

-- 1. Nguoi dong cung (null = dong rieng). staff van la nguoi dung quet.
alter table public.warehouse_outbound_checks add column if not exists co_staff text;
alter table public.warehouse_outbound_checks
  drop constraint if exists warehouse_outbound_co_staff_chk;
alter table public.warehouse_outbound_checks
  add constraint warehouse_outbound_co_staff_chk
  check (co_staff is null or lower(trim(co_staff)) <> lower(trim(coalesce(staff,''))));

-- 2. Log bat/tat "Dong chung" (ai, luc nao, voi ai). action: on | off | auto_off
create table if not exists public.warehouse_copack_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  scan_date date,
  action text not null check (action in ('on','off','auto_off')),
  staff text,
  co_staff text
);

-- 3. Log sua hang loat (quan ly). before_data luu gia tri cu tung don de khoi phuc khi can.
create table if not exists public.warehouse_outbound_bulk_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  by_staff text,
  scan_date date,
  from_time text,
  to_time text,
  filter_staff text,
  new_staff text,
  new_co_staff text,          -- '' = da bo (dong rieng); null = khong doi
  n_rows int,
  before_data jsonb
);

-- 4. Quyen: giong cac bang warehouse_* hien co (app dung khoa anon). Neu cac bang kia dang BAT RLS thi
--    doi 2 dong "disable" thanh policy tuong ung; hien tai lam giong bang warehouse_unpacked_log.
alter table public.warehouse_copack_log disable row level security;
alter table public.warehouse_outbound_bulk_log disable row level security;
grant select, insert, update, delete on public.warehouse_copack_log, public.warehouse_outbound_bulk_log to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
