-- 1. Danh sach don da co ma van don (TikTok "Cho lay hang" / Shopee "Da xu ly") ma hang CHUA lay luc 20:00.
--    Job 20:00 tren PC (tools/sync_late_orders.py) ghi lai TOAN BO moi toi: don nao hang da lay thi tu mat.
--    da_tich = luc quet, ma van don da co trong "Tich don di" hay chua:
--      false -> nhom "Da in phieu, chua dong": So Kho tu bo khoi canh bao ngay khi ban kho tich don di.
--      true  -> nhom "Da dong, hang chua lay" (kien bo sot): giu den lan quet 20:00 sau.
create table if not exists public.warehouse_late_orders (
  ma_van_don text primary key,
  san text not null,                        -- tiktok | shopee
  ma_don text,                              -- ma don cua san
  tao_luc timestamptz,                      -- gio khach dat
  han date not null,                        -- han phai di: dat truoc 16:00 -> trong ngay, sau 16:00 -> hom sau
  da_tich boolean not null default false,
  tich_boi text,
  tich_luc timestamptz,
  quet_luc timestamptz not null             -- gio job quet (So Kho hien "Cap nhat ...")
);

-- 2. Ai da xem danh sach don tre dau ca (man chan dau ca). Moi nguoi moi ngay 1 dong.
create table if not exists public.warehouse_late_ack (
  id bigint generated by default as identity primary key,
  ngay date not null,
  staff text not null,
  so_don int not null default 0,
  created_at timestamptz not null default now(),
  unique (ngay, staff)
);

-- 3. Quyen: giong cac muc truoc
alter table public.warehouse_late_orders disable row level security;
alter table public.warehouse_late_ack disable row level security;
grant select, insert, update, delete on public.warehouse_late_orders, public.warehouse_late_ack to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
